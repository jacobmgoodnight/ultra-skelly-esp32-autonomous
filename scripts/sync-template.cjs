// Canonical firmware stays editable in Arduino; Studio embeds it for offline use.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "firmware/SkellyAutonomous/SkellyAutonomous.ino"), "utf8").replace(/\r\n/g, "\n");
const target = path.join(root, "studio/template.js");
const expected = "// Generated by node scripts/sync-template.cjs; edit the canonical .ino instead.\n" +
  "window.SKELLY_FIRMWARE_TEMPLATE = " + JSON.stringify(source) + ";\n";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== expected) {
    console.error("Firmware template is stale. Run: node scripts/sync-template.cjs");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, expected);
}
