"""Prepare a local, matched-level listening page from existing preview WAVs."""
from pathlib import Path
import html
import sys

import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

root = Path('.').resolve()
samples = root / '.skelly-build/voice-research/samples'
sys.path.insert(0, str(root / 'experiments/local-talkback'))
from voice import validate_reply_wave

sources = [
    ('adam', 'MOSS Adam', 'character-adam-1.wav'),
    ('supertonic', 'Supertonic M1', 'character-supertonic-1.wav'),
    ('qwen1', 'Qwen: playful storyteller requested', 'qwen-demo-spooky-1.wav'),
    ('qwen2', 'Qwen: theatrical and mischievous requested', 'qwen-demo-spooky-2.wav'),
    ('qwen3', 'Qwen: whispery storyteller requested', 'qwen-demo-spooky-3.wav'),
]
loaded = []
for key, label, filename in sources:
    audio, rate = sf.read(samples / filename, dtype='float64')
    if audio.ndim != 1 or len(audio) == 0 or not np.isfinite(audio).all():
        raise ValueError(f'Invalid audio: {filename}')
    if rate == 24000:
        audio = resample_poly(audio, 147, 160)
    elif rate != 22050:
        raise ValueError(f'Unexpected sample rate: {filename}')
    if len(audio) > 8 * 22050:
        raise ValueError(f'Preview exceeds the existing eight-second reply bound: {filename}')
    rms = float(np.sqrt(np.mean(audio * audio)))
    peak = float(np.max(np.abs(audio)))
    if rms < 1e-5 or peak <= 0:
        raise ValueError(f'No audible signal: {filename}')
    loaded.append((key, label, audio, rms, peak))

# Turn louder samples down only; keep the result below full scale after resampling.
target = min(min(item[3] for item in loaded), min(item[3] * 0.95 / item[4] for item in loaded))
labels = []
for key, label, audio, rms, _ in loaded:
    destination = samples / f'qwen-comparison-{key}.wav'
    sf.write(destination, audio * (target / rms), 22050, subtype='PCM_16')
    validate_reply_wave(destination.read_bytes())
    labels.append(f'<label>{html.escape(label)}<audio controls preload="none" src="{destination.name}"></audio></label>')

page = '''<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Skelly voice-design comparison</title>
<style>body{font:18px system-ui;background:#171324;color:#f8f4ff;max-width:58rem;margin:auto;padding:1.5rem}
section{padding:1rem;margin:1rem 0;border:1px solid #a491ca;border-radius:.7rem}
label{display:block;margin:1rem 0}audio{display:block;width:min(100%,34rem);margin-top:.4rem}</style>
<h1>Skelly voice-design comparison</h1>
<p>Start at low volume and play one sample at a time. All use the same ghost joke;
average levels were matched by turning louder recordings down.</p>
<p>The three Qwen previews were generated by Qwen's public online demo using only
the fixed joke and fictional voice descriptions. MOSS Adam and Supertonic were
generated locally. The requested voice descriptions are labels, not guarantees
about what the model produced. Generated speech can differ from the written text;
review it before use around children.</p>
<p>This page only plays existing files. It does not open the microphone, send data,
or connect to Skelly.</p><section><h2>Ghost joke</h2>
<p>Why did the ghost wear glasses? To improve its spook tacles!</p>'''
page += ''.join(labels) + '</section></html>'
(samples / 'compare-qwen-design.html').write_text(page, encoding='utf-8')
print(f'Prepared {len(labels)} validated, matched-level previews.')
