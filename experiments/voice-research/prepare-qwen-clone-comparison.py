"""Prepare local playback comparisons from already generated synthetic clips."""
import html
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

root = Path('.').resolve()
samples = root / '.skelly-build/voice-research/samples'
sys.path.insert(0, str(root / 'experiments/local-talkback'))
from voice import validate_reply_wave

metrics = json.loads((root / '.skelly-build/voice-research/qwen-clone-metrics.json').read_text(encoding='utf-8'))
for name in ('xvector-intro', 'icl-intro', 'icl-skeleton'):
    matching = [row for row in metrics if row.get('name') == name]
    if len(matching) != 1 or matching[0].get('exit_code') != 0 or not matching[0].get('eos_seen'):
        raise ValueError(f'Generation did not complete for {name}')
    path = samples / f'qwen-clone-{name}-raw.wav'
    if hashlib.sha256(path.read_bytes()).hexdigest() != matching[0].get('sha256'):
        raise ValueError(f'Generated audio does not match recorded hash for {name}')

sources = [
    ('reference', 'Original theatrical Qwen · ghost joke', 'qwen-comparison-qwen2.wav'),
    ('moss', 'MOSS voice you liked · introduction', 'moss-qwen-reference-intro.wav'),
    ('a', 'Qwen local voice match A · introduction', 'qwen-clone-xvector-intro-raw.wav'),
    ('b', 'Qwen local voice match B · introduction', 'qwen-clone-icl-intro-raw.wav'),
    ('b2', 'Qwen local voice match B · skeleton joke', 'qwen-clone-icl-skeleton-raw.wav'),
]
items = []
for key, label, filename in sources:
    audio, rate = sf.read(samples / filename, dtype='float64')
    if audio.ndim != 1 or not len(audio) or not np.isfinite(audio).all():
        raise ValueError(f'Invalid audio: {filename}')
    if rate == 24000:
        audio = resample_poly(audio, 147, 160)
    elif rate != 22050:
        raise ValueError(f'Unexpected sample rate: {filename}')
    if len(audio) > 22050 * 8:
        raise ValueError(f'Audio exceeds current duration bound: {filename}')
    rms, peak = float(np.sqrt(np.mean(audio * audio))), float(np.max(np.abs(audio)))
    if rms < 1e-5 or peak <= 0:
        raise ValueError(f'No audible signal: {filename}')
    items.append((key, label, audio, rms, peak))
target = min(min(x[3] for x in items), min(x[3] * 0.95 / x[4] for x in items))
labels = []
for key, label, audio, rms, _ in items:
    output = samples / f'qwen-clone-comparison-{key}.wav'
    sf.write(output, audio * (target / rms), 22050, subtype='PCM_16')
    validate_reply_wave(output.read_bytes())
    labels.append(f'<label>{html.escape(label)}<audio controls preload="none" src="{output.name}"></audio></label>')

page = '''<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Skelly Qwen voice matching</title>
<style>body{font:18px system-ui;background:#171324;color:#f8f4ff;max-width:58rem;margin:auto;padding:1.5rem}
section{padding:1rem;margin:1rem 0;border:1px solid #a491ca;border-radius:.7rem}
label{display:block;margin:1rem 0}audio{display:block;width:min(100%,34rem);margin-top:.4rem}</style>
<h1>Can Qwen keep the same character?</h1>
<p>Start at low volume. The original theatrical Qwen joke is the reference. The
new local Qwen samples try to follow that voice; A uses its voice alone, while B
also uses the reference's written words. MOSS is included for context. Average
levels were matched by turning louder recordings down.</p>
<p>The reference was generated by Qwen's public demo. The matching samples were
generated locally from that fictional synthetic voice, with no visitor recording.
These are previews; listen to the actual words before any use around children.
This page only plays saved files; it does not open the microphone or connect to Skelly.</p>
<section><h2>Original voice reference</h2><p>Why did the ghost wear glasses? To improve its spook tacles!</p>'''
page += labels[0] + '</section><section><h2>Same introduction</h2>'
page += '<p>I am Skelly, the friendly skeleton. Chief officer of silly Halloween jokes!</p>'
page += ''.join(labels[1:4]) + '</section><section><h2>Another Qwen line</h2>'
page += '<p>Why did the skeleton skip the party? He had no body to go with!</p>'
page += labels[4] + '</section></html>'
(samples / 'compare-qwen-clone.html').write_text(page, encoding='utf-8')
print(f'Prepared {len(labels)} validated, matched-level Qwen clone previews.')
